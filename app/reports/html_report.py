import json
import os
from datetime import datetime

class ReportGenerator:
    def __init__(self, session_log_dir, project_root, platform_info):
        self.session_log_dir = session_log_dir
        self.project_root = project_root
        self.platform_info = platform_info
        
    def generate(self) -> str:
        # Load diagnostics
        diag_path = os.path.join(self.session_log_dir, "diagnostics.json")
        diagnostics = []
        if os.path.exists(diag_path):
            with open(diag_path, 'r') as f:
                for line in f:
                    if line.strip():
                        diagnostics.append(json.loads(line))
                        
        # Load actions
        audit_path = os.path.join(self.session_log_dir, "actions.json")
        actions = []
        if os.path.exists(audit_path):
            with open(audit_path, 'r') as f:
                for line in f:
                    if line.strip():
                        actions.append(json.loads(line))
                        
        # Determine overall status
        overall_status = "PASS"
        for d in diagnostics:
            if d.get('status') == "FAIL":
                overall_status = "FAIL"
                break
            elif d.get('status') == "WARNING" and overall_status == "PASS":
                overall_status = "WARNING"

        # Build HTML
        html = f"""<!DOCTYPE html>
<html>
<head>
    <title>Portable SysAdmin Diagnostic Report</title>
    <style>
        body {{ font-family: Arial, sans-serif; margin: 40px; color: #333; }}
        h1, h2, h3 {{ color: #2C3E50; border-bottom: 2px solid #2C3E50; padding-bottom: 5px; }}
        .header-block {{ background-color: #ECF0F1; padding: 20px; border-radius: 5px; margin-bottom: 30px; }}
        .status-PASS {{ color: green; font-weight: bold; }}
        .status-FAIL {{ color: red; font-weight: bold; }}
        .status-WARNING {{ color: orange; font-weight: bold; }}
        table {{ width: 100%; border-collapse: collapse; margin-top: 15px; }}
        th, td {{ border: 1px solid #BDC3C7; padding: 10px; text-align: left; }}
        th {{ background-color: #ECF0F1; }}
        .pre-evidence {{ background: #272822; color: #F8F8F2; padding: 10px; border-radius: 4px; overflow-x: auto; font-family: monospace; }}
    </style>
</head>
<body>
    <h1>Portable SysAdmin Diagnostic Report</h1>
    
    <div class="header-block">
        <p><strong>Machine:</strong> {self.platform_info.get('hostname', 'Unknown')}</p>
        <p><strong>OS:</strong> {self.platform_info.get('os')} ({self.platform_info.get('release')})</p>
        <p><strong>Date:</strong> {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}</p>
        <p><strong>Overall Status:</strong> <span class="status-{overall_status}">{overall_status}</span></p>
    </div>

    <h2>Diagnostic Summary</h2>
    <table>
        <tr><th>Category</th><th>Test</th><th>Status</th><th>Severity</th></tr>
"""
        for d in diagnostics:
            st = d.get('status', 'UNKNOWN')
            html += f"        <tr><td>{d.get('category')}</td><td>{d.get('test')}</td><td class='status-{st}'>{st}</td><td>{d.get('severity')}</td></tr>\n"

        html += """    </table>

    <h2>Detailed Findings</h2>
"""
        for d in diagnostics:
            if d.get('status') in ['FAIL', 'WARNING']:
                html += f"""    <h3>[{d.get('severity')}] {d.get('message')}</h3>
    <p><strong>Category:</strong> {d.get('category')} | <strong>Test:</strong> {d.get('test')}</p>
    <div class="pre-evidence">
{json.dumps(d.get('evidence', {}), indent=2)}
    </div>
"""
        
        html += """
    <h2>Remediation Actions Taken</h2>
"""
        if not actions:
            html += "<p>No remediation actions were executed during this session.</p>"
        else:
            html += """    <table>
        <tr><th>Time</th><th>Action</th><th>Risk</th><th>Success</th><th>Message</th></tr>
"""
            for a in actions:
                st = "PASS" if a.get('success') else "FAIL"
                html += f"        <tr><td>{a.get('timestamp')[:19]}</td><td>{a.get('action_name')}</td><td>{a.get('risk')}</td><td class='status-{st}'>{st}</td><td>{a.get('message')}</td></tr>\n"
            html += "    </table>\n"

        html += """
    <hr style="margin-top: 50px;">
    <p style="text-align: center; color: #7F8C8D; font-size: 0.9em;">Generated by Portable SysAdmin Toolkit</p>
</body>
</html>
"""
        # Save report
        out_file = os.path.join(self.session_log_dir, "final-report.html")
        with open(out_file, 'w') as f:
            f.write(html)
            
        return out_file
